#!/usr/bin/env python3
"""Generate compact LVGL 8 fonts from OFL Noto Sans CJK (Pillow required)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
# ASCII, Latin-1 (including · and ×), punctuation, kana, CJK, fullwidth.
POINTS = list(range(32, 127)) + list(range(0xA0, 0x100)) + list(range(0x2000, 0x2070)) + list(range(0x3000, 0x3100)) + list(range(0x3400, 0xA000)) + list(range(0xFF00, 0xFFF0))
OUT = ROOT / 'firmware/hud'
HEADER = '''#pragma once
#include <lvgl.h>
extern lv_font_t hud_font_24;
extern lv_font_t hud_font_28;
void hud_fonts_init();
'''
SOURCE = '''// Generated by scripts/build-fonts.py; Noto Sans CJK, SIL OFL 1.1.
#include "HudFonts.h"
struct Glyph { uint32_t offset; uint16_t code; uint8_t w,h,advance; int8_t x,y; };
struct FontData { const Glyph *glyphs; const uint8_t *bitmap; size_t count; };
static const Glyph *findGlyph(const lv_font_t *font, uint32_t code) {
 const FontData *d = (const FontData *)font->dsc;
 size_t lo=0, hi=d->count;
 while(lo<hi) { size_t mid=(lo+hi)/2; if(d->glyphs[mid].code<code) lo=mid+1; else hi=mid; }
 return lo<d->count && d->glyphs[lo].code==code ? d->glyphs+lo : nullptr;
}
static bool describe(const lv_font_t *f, lv_font_glyph_dsc_t *out, uint32_t c, uint32_t) {
 const Glyph *g=findGlyph(f,c); if(!g) return false;
 out->adv_w=g->advance; out->box_w=g->w; out->box_h=g->h;
 out->ofs_x=g->x; out->ofs_y=g->y; out->bpp=1; out->is_placeholder=0; return true;
}
static const uint8_t *bitmap(const lv_font_t *f,uint32_t c) {
 const Glyph *g=findGlyph(f,c); return g ? ((const FontData *)f->dsc)->bitmap+g->offset : nullptr;
}
'''
with (OUT / 'HudFonts.cpp').open('w') as out:
    out.write(SOURCE)
    for size in (24, 28):
        font = ImageFont.truetype(str(ROOT / 'assets/fonts/NotoSansCJKsc-Regular.otf'), size)
        data = bytearray()
        glyphs = []
        for cp in POINTS:
            s = chr(cp)
            x0,y0,x1,y1 = font.getbbox(s, anchor='ls')
            w,h = x1-x0,y1-y0
            canvas = Image.new('L', (max(1,w),max(1,h)))
            ImageDraw.Draw(canvas).text((-x0,-y0),s,font=font,fill=255,anchor='ls')
            glyphs.append((len(data),cp,w,h,round(font.getlength(s)),x0,-y1))
            values = list(canvas.getdata()) if w*h else []
            for i in range(0,len(values),8):
                data.append(sum((v>=112) << (7-j) for j,v in enumerate(values[i:i+8])))
        out.write(f'static const uint8_t bits{size}[]={{\n')
        for i in range(0,len(data),32): out.write(','.join(map(str,data[i:i+32]))+',\n')
        out.write('};\n'+f'static const Glyph glyphs{size}[]={{\n')
        for g in glyphs: out.write('{'+','.join(map(str,g))+'},\n')
        out.write('};\n'+f'static const FontData data{size}={{glyphs{size},bits{size},{len(glyphs)}}};\n')
        out.write(f'lv_font_t hud_font_{size};\n')
        print(size,len(glyphs),'glyphs',len(data),'bitmap bytes')
    out.write('void hud_fonts_init() {\n')
    for size in (24,28):
        out.write(f'hud_font_{size}={{}}; hud_font_{size}.get_glyph_dsc=describe; hud_font_{size}.get_glyph_bitmap=bitmap; hud_font_{size}.line_height={size+8}; hud_font_{size}.base_line=8; hud_font_{size}.dsc=&data{size};\n')
    out.write('}\n')
(OUT/'HudFonts.h').write_text(HEADER)
